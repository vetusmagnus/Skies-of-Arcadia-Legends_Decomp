#!/usr/bin/env python3
"""Emit a range of the original .rodata as C objects, for a file whose functions reach their data
through the section base (`lis rX, lbl_xxx@ha; addi rX, rX, lbl_xxx@l` then fixed offsets).

usage: gen_rodata.py START_HEX END_HEX [overrides.py] > out.c
Each object spans from its address to the next boundary (dtk's symbols plus EXTRA split points), so
padding and alignment come out exactly. Strings become char arrays, objects holding relocations
become pointer tables, the rest u32/u8 arrays. overrides.py may define OVERRIDES = {addr: C text}
for objects given real types (the text must define the object at exactly that size)."""
import os, re, struct, sys

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
START = int(sys.argv[1], 16)
END = int(sys.argv[2], 16)
# Extra object boundaries (base-register offsets that dtk has no symbol for) come from overrides.py.
EXTRA = []
dol = open(R + "/orig/GEAE8P/sys/main.dol", "rb").read()
offs = struct.unpack(">18I", dol[0:72]); addrs = struct.unpack(">18I", dol[72:144]); sizes = struct.unpack(">18I", dol[144:216])


def rd(a, n):
    for o, ad, s in zip(offs, addrs, sizes):
        if ad <= a < ad + s:
            return dol[o + a - ad:o + a - ad + n]


OVERRIDES = {}
if len(sys.argv) > 3:
    ns = {"rd": rd, "R": R}
    exec(open(sys.argv[3]).read(), ns)
    OVERRIDES = ns.get("OVERRIDES", {})
    EXTRA += ns.get("EXTRA", [])


syms, strings = {}, set()
for l in open(R + "/config/GEAE8P/symbols.txt"):
    m = re.match(r"(\S+) = \.rodata:0x(\w+); // type:object size:0x(\w+)(.*)", l)
    if m:
        a = int(m.group(2), 16)
        if START <= a < END:
            syms[a] = m.group(1)
            if "data:string" in m.group(4):
                strings.add(a)

# Relocations: walk dtk's listing of each object (pointer tables are plain .4byte lines).
relocs = {}
asm = open(R + "/build/GEAE8P/asm/auto_04_802AD360_rodata.s").read()
for m in re.finditer(r"^\.obj (lbl_(\w{8})), \w+\n(.*?)^\.endobj \1", asm, re.S | re.M):
    a = int(m.group(2), 16)
    if not (START <= a < END) or not re.search(r"\.4byte [A-Za-z_]", m.group(3)):
        continue
    lines = [x.strip() for x in m.group(3).split("\n") if x.strip()]
    assert all(x.startswith(".4byte") for x in lines), m.group(1)
    for i, x in enumerate(lines):
        v = x.split()[1]
        if re.match(r"[A-Za-z_]", v):
            relocs[a + 4 * i] = v

bounds = sorted(set(list(syms) + [e for e in EXTRA if START <= e < END] + [START, END]))
targets = sorted(set(re.sub(r"\+.*", "", v) for v in relocs.values()))


def name(a):
    return "lbl_%08X" % a


def ctype(a, n):
    if a in OVERRIDES:
        return None
    if any(a <= r < a + n for r in relocs):
        return "const void* const"
    if a in strings:
        return "const char"
    return "const u32" if n % 4 == 0 else "const u8"


def cstr(b):
    out = ""
    for i, c in enumerate(b):
        if c == 0x22 or c == 0x5C:
            out += "\\" + chr(c)
        elif 0x20 <= c < 0x7F:
            out += chr(c)
        else:
            out += "\\%03o" % c
    return out


objs = []
for a, b in zip(bounds, bounds[1:]):
    objs.append((a, b - a))
# Forward declarations for the targets of pointer words.
print("/* .rodata 0x%08X-0x%08X of the original (generated by tools/match/gen_rodata.py from the DOL)." % (START, END))
print(" * Objects are sized to the next one, padding included. */")
for t in targets:
    a = int(t[4:], 16)
    n = dict(objs)[a]
    ty = ctype(a, n)
    if ty:
        print("extern %s %s[];" % (ty, t))
for a, n in objs:
    assert n > 8, "object at %08X would go to .sdata2" % a
    if a in OVERRIDES:
        print(OVERRIDES[a].strip())
        continue
    ty = ctype(a, n)
    data = rd(a, n)
    if ty == "const char":
        body = data.rstrip(b"\0")
        print('%s %s[0x%X] = "%s";' % (ty, name(a), n, cstr(body)))
    elif ty == "const void* const":
        assert n % 4 == 0
        items = []
        for i in range(0, n, 4):
            r = relocs.get(a + i)
            if r:
                m = re.match(r"(\w+)(?:\+0x(\w+))?", r)
                items.append("(const u8*)%s + 0x%X" % (m.group(1), int(m.group(2), 16)) if m.group(2) else m.group(1))
            else:
                items.append("(const void*)0x%08X" % struct.unpack(">I", data[i:i + 4])[0])
        print("%s %s[%d] = {\n    %s,\n};" % (ty, name(a), n // 4, ",\n    ".join(items)))
    elif ty == "const u32":
        w = struct.unpack(">%dI" % (n // 4), data)
        rows = [", ".join("0x%08X" % x for x in w[i:i + 6]) for i in range(0, len(w), 6)]
        print("%s %s[%d] = {\n    %s,\n};" % (ty, name(a), n // 4, ",\n    ".join(rows)))
    else:
        rows = [", ".join("0x%02X" % x for x in data[i:i + 12]) for i in range(0, n, 12)]
        print("%s %s[%d] = {\n    %s,\n};" % (ty, name(a), n, ",\n    ".join(rows)))

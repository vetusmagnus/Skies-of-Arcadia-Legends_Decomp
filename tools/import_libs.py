#!/usr/bin/env python3
"""Import matching library source (SDK / MSL / TRK, MusyX) from other decomp projects.

tw2004 (https://github.com/mitsevox/tw2004) links the same Dolphin SDK build as Skies
(Sep 5 2002, 0x2301) and vendors matched library source from several CC0/MIT projects under
extern/. MusyX (extern/musyx) is vendored here directly; see LOCAL_LIBS. This script:

  1. copies the extern/ trees we use (never gauntlet: no license) and tw2004's three glue
     headers into this repo, without overwriting local edits
  2. compiles every completed tw2004 library object with tw2004's exact flags, plus every
     LOCAL_LIBS object with its library's flags
  3. keeps only objects that tools/tusplit.py can place in main.dol with matching code,
     function order, data contents and no extra data
  4. rewrites the generated splits.txt entries and the configure.py block, fixes split
     boundaries (tools/fixsplits.py) and names the symbols involved in symbols.txt

Usage:
    git clone https://github.com/mitsevox/tw2004 /path/to/tw2004
    git -C /path/to/tw2004 checkout e90a46609ba8ec4d2e656aa1dc4d6c858d246ca3
    python tools/import_libs.py /path/to/tw2004
    python configure.py && ninja
"""

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "config" / "GEAE8P"
MANIFEST = CONFIG / "lib_import.json"
WORK = ROOT / "build" / "import_libs"
TREES = ["sdk", "ffcc", "trk", "tww", "tp", "sonicheroes", "pikmin2"]  # not gauntlet: no license
GLUE_HEADERS = ["types.h", "asm_types.h", "GameVersions.h"]
BEGIN = "# BEGIN library import (generated by tools/import_libs.py)"
END = "# END library import"

EXCLUDE = set()

# Copies of a file in another vendored tree that match Skies where tw2004's choice doesn't. Each
# is compiled with the flags of the tw2004 object named second (same tree and library).
ALTERNATES = [
    ("extern/sdk/dolphin/card/CARDBios.c", "extern/sdk/dolphin/card/CARDRead.c"),  # Sep 2002 build
    ("extern/sdk/dolphin/card/CARDOpen.c", "extern/sdk/dolphin/card/CARDRead.c"),
    ("extern/sdk/dolphin/card/CARDStat.c", "extern/sdk/dolphin/card/CARDRead.c"),
    ("extern/sdk/dolphin/card/CARDWrite.c", "extern/sdk/dolphin/card/CARDRead.c"),  # pre-2003 branch
]

# Same object, different names across source trees. extern/sdk calls the GX state pointer
# __GXData; dtk's signature database calls it gx.
RENAME = {"gx": "__GXData"}

# Libraries vendored in this repo rather than taken from tw2004. Every source file is a candidate.
MUSYX_CFLAGS = [
    "-proc gekko", "-nodefaults", "-nosyspath", "-i include", "-i include/compat", "-i extern/sdk/include",
    "-i extern/musyx/include", "-i extern/sdk/libc", "-inline auto,depth=4", "-O4,p", "-fp hard",
    "-enum int", "-sym on", "-Cpp_exceptions off", "-str reuse,pool,readonly", "-fp_contract off",
    "-DMUSY_TARGET=MUSY_TARGET_DOLPHIN",
    "-DMUSY_VERSION_MAJOR=2", "-DMUSY_VERSION_MINOR=0", "-DMUSY_VERSION_PATCH=0",
]
LOCAL_LIBS = [
    # Same compiler and flags as Metroid Prime's MusyX 2.0.0 (PrimeDecomp/prime configure.py).
    dict(lib="musyx", mw="GC/1.3.2", cflags=MUSYX_CFLAGS, src_dir="extern/musyx/src",
         sources="musyx/runtime/**/*.c", progress_category="middleware"),
]

# tw2004's flags, adjusted for Skies. Skies' memory card library predates the 2003 CARD patch
# (CARDReadAsync calls __CARDAccess, then __CARDIsWritable on CARD_RESULT_NOPERM).
FLAG_SUBST = {"GW4E69": "GEAE8P", "-DCARD_PATCH_2003=1": "-DCARD_PATCH_2003=0"}


def skies_flag(flag):
    for a, b in FLAG_SUBST.items():
        flag = flag.replace(a, b)
    return flag


def load_tw2004(tw):
    sys.path.insert(0, str(tw))
    argv, sys.argv = sys.argv, ["configure.py", "configure"]
    import tools.project as project  # tw2004's copy

    project.generate_build = lambda *a, **k: None
    g = {"__name__": "__main__", "__file__": str(tw / "configure.py")}
    cwd = Path.cwd()
    try:
        import os
        os.chdir(tw)
        exec(compile((tw / "configure.py").read_text(), "configure.py", "exec"), g)
    finally:
        os.chdir(cwd)
        sys.argv = argv
    return g["config"]


def copy_sources(tw):
    copied = []
    for tree in TREES:
        dst = ROOT / "extern" / tree
        if not dst.exists() and (tw / "extern" / tree).exists():
            shutil.copytree(tw / "extern" / tree, dst)
            copied.append(tree)
    (ROOT / "include").mkdir(exist_ok=True)
    for h in GLUE_HEADERS:
        if not (ROOT / "include" / h).exists():
            shutil.copy(tw / "include" / h, ROOT / "include" / h)
    return copied


def candidates(config):
    out = []
    for lib in config.libs:
        for obj in lib["objects"]:
            if not obj.completed:
                continue
            o = obj.resolve(config, lib)
            src = Path(o.options["src_dir"]) / o.options["source"]
            if len(src.parts) < 3 or src.parts[0] != "extern" or src.parts[1] not in TREES:
                continue
            if src.name in EXCLUDE or src.suffix not in (".c", ".cpp"):
                continue
            mw = o.options["mw_version"]
            if str(mw).startswith("ProDG"):
                continue
            out.append(dict(lib=lib["lib"], name=obj.name, src=str(src), mw=mw,
                            obj_mw=obj.options.get("mw_version"), extra=obj.options.get("extra_cflags") or [],
                            lib_mw=lib["mw_version"], cflags=list(lib["cflags"]), src_dir=lib.get("src_dir")))
    for lib in LOCAL_LIBS:
        for src in sorted((ROOT / lib["src_dir"]).glob(lib["sources"])):
            out.append(dict(lib=lib["lib"], name=str(src.relative_to(ROOT / lib["src_dir"])),
                            src=str(src.relative_to(ROOT)), mw=lib["mw"], obj_mw=None, extra=[],
                            lib_mw=lib["mw"], cflags=list(lib["cflags"]), src_dir=lib["src_dir"],
                            progress_category=lib["progress_category"]))
    for alt, like in ALTERNATES:
        c = next(c for c in out if c["src"] == like)
        out.append(dict(c, src=alt, name=str(Path(alt).relative_to(c["src_dir"])), alt=True))
    return out


def compile_one(c):
    out = WORK / "obj" / (c["src"].replace("/", "__") + ".o")
    flags = " ".join(skies_flag(f) for f in c["cflags"] + c["extra"])
    cmd = [str(ROOT / "build/compilers" / c["mw"] / "mwcceppc.exe"), *shlex.split(flags), "-c", c["src"], "-o", str(out)]
    if os.name != "nt":
        cmd.insert(0, str(ROOT / "build/tools/wibo"))
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    return out if r.returncode == 0 and out.exists() else None


def place(c, objfile):
    r = subprocess.run([sys.executable, str(ROOT / "tools/tusplit.py"), str(objfile), "--name", c["name"], "--symbols"],
                       capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        return None
    secs, syms = {}, []
    for line in r.stdout.splitlines()[1:]:
        m = re.match(r"\s+(\S+)\s+start:0x([0-9A-F]+) end:0x([0-9A-F]+)", line)
        if m:
            secs[m.group(1)] = (int(m.group(2), 16), int(m.group(3), 16))
        m = re.match(r"# sym ([0-9A-F]{8}) (\S+) (local|global)", line)
        if m:
            syms.append((int(m.group(1), 16), m.group(2), m.group(3)))
    if not secs:
        return None  # nothing of its own in the DOL
    nfound = int(re.search(r"# (\d+)/\d+ functions", r.stderr).group(1))
    split_text = "\n".join(l for l in r.stdout.splitlines() if not l.startswith("# sym"))
    return dict(c, secs=secs, syms=syms, nfound=nfound, splits=split_text)


def select(placed):
    best = {}
    for p in placed:
        k = p["secs"][".text"][0] if ".text" in p["secs"] else min(a for a, _ in p["secs"].values())
        rank = lambda q: (q["nfound"], q.get("alt", False))  # alternates win ties
        if k not in best or rank(p) > rank(best[k]):
            best[k] = p
    final = []
    for p in sorted(best.values(), key=lambda p: min(a for a, _ in p["secs"].values())):
        clash = any(s in f["secs"] and a < f["secs"][s][1] and f["secs"][s][0] < b
                    for f in final for s, (a, b) in p["secs"].items())
        if not clash:
            final.append(p)
    return final


def write_splits(final):
    text = (CONFIG / "splits.txt").read_text()
    old = json.loads(MANIFEST.read_text())["objects"] if MANIFEST.exists() else []
    blocks = re.split(r"\n(?=\S)", text)
    blocks = [b for b in blocks if b.split(":", 1)[0] not in old]
    text = "\n".join(blocks).rstrip("\n") + "\n"
    for p in final:
        text += "\n" + p["splits"].rstrip("\n") + "\n"
    (CONFIG / "splits.txt").write_text(text)


def write_configure(final):
    libs = {}
    for p in final:
        libs.setdefault(p["lib"], dict(mw=p["lib_mw"], src_dir=p["src_dir"], objs=[],
                                       category=p.get("progress_category", "sdk"),
                                       cflags=[skies_flag(s) for s in p["cflags"]]))["objs"].append(p)
    out = [BEGIN, "# Library code borrowed from other decomp projects; see extern/*/README.md for sources",
           "# and licenses. Placement in main.dol was verified with tools/tusplit.py.", "config.libs += ["]
    for name, l in libs.items():
        out += ["    {", f'        "lib": {json.dumps(name)},', f'        "mw_version": {json.dumps(l["mw"])},',
                f'        "cflags": {json.dumps(l["cflags"])},', f'        "progress_category": {json.dumps(l["category"])},']
        if l["src_dir"]:
            out.append(f'        "src_dir": {json.dumps(l["src_dir"])},')
        out.append('        "objects": [')
        for p in l["objs"]:
            opts = ""
            if p["obj_mw"] and p["obj_mw"] != l["mw"]:
                opts += f", mw_version={json.dumps(p['obj_mw'])}"
            if p["extra"]:
                opts += f", extra_cflags={json.dumps(p['extra'])}"
            out.append(f'            Object(Matching, {json.dumps(p["name"])}{opts}),')
        out += ["        ],", "    },"]
    out += ["]", END]
    s = (ROOT / "configure.py").read_text()
    if BEGIN in s:
        s = s[:s.index(BEGIN)] + "\n".join(out) + s[s.index(END) + len(END):]
    else:
        anchor = "\n\n# Optional callback to adjust link order."
        s = s.replace(anchor, "\n\n" + "\n".join(out) + anchor, 1)
    (ROOT / "configure.py").write_text(s)
    return len(libs)


def write_symbols(final):
    defs, refs = {}, {}
    for p in final:
        for a, name, scope in p["syms"]:
            inside = any(lo <= a < hi for lo, hi in p["secs"].values())
            (defs if inside else refs).setdefault(a, (name, scope))
    names = dict(refs)
    names.update(defs)
    lines = (CONFIG / "symbols.txt").read_text().splitlines()
    done = set()
    for i, line in enumerate(lines):
        m = re.match(r"^(\S+) = (\.\w+):0x([0-9A-F]+); // (.*)$", line)
        if not m:
            continue
        cur = m.group(1)
        if cur in RENAME:
            line = lines[i] = line.replace(f"{cur} = ", f"{RENAME[cur]} = ", 1)
            cur = RENAME[cur]
        a = int(m.group(3), 16)
        if "type:label" in m.group(4) or a not in names or a in done:
            continue
        name, scope = names[a]
        # keep names dtk already knew unless we define the symbol ourselves
        if cur != name and not cur.startswith(("fn_", "lbl_")) and a not in defs:
            done.add(a)
            continue
        # dtk's canonical attribute order: type, size, scope, align, data
        attrs = re.sub(r"\s*scope:\w+", "", m.group(4)).strip().split()
        pos = next((k + 1 for k, t in enumerate(attrs) if t.startswith("size:")), 1)
        attrs.insert(pos, f"scope:{scope}")
        lines[i] = f"{name} = {m.group(2)}:0x{a:08X}; // {' '.join(attrs)}"
        done.add(a)
    (CONFIG / "symbols.txt").write_text("\n".join(lines) + "\n")
    return len(defs), len(refs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tw2004", type=Path, help="path to a mitsevox/tw2004 checkout")
    args = ap.parse_args()
    tw = args.tw2004.resolve()

    config = load_tw2004(tw)
    copied = copy_sources(tw)
    cands = candidates(config)
    (WORK / "obj").mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(8) as ex:
        objs = list(ex.map(compile_one, cands))
    built = [(c, o) for c, o in zip(cands, objs) if o]
    print(f"compiled {len(built)}/{len(cands)} candidate objects")
    with ThreadPoolExecutor(8) as ex:
        placed = [p for p in ex.map(lambda co: place(*co), built) if p]
    final = select(placed)
    print(f"{len(placed)} placed cleanly by tusplit; {len(final)} selected")

    used = {Path(p["src"]).parts[1] for p in final}
    for tree in copied:
        if tree not in used:
            shutil.rmtree(ROOT / "extern" / tree)  # copied for this run but nothing matched

    write_splits(final)
    nlibs = write_configure(final)
    subprocess.run([sys.executable, str(ROOT / "tools/fixsplits.py")], cwd=ROOT, check=True)
    ndefs, nrefs = write_symbols(final)
    local = {l["lib"] for l in LOCAL_LIBS}
    MANIFEST.write_text(json.dumps({
        "sources": {
            "tw2004": "https://github.com/mitsevox/tw2004",
            **{l["lib"]: l["src_dir"].split("/src")[0] for l in LOCAL_LIBS},
        },
        "counts": {
            "tw2004": sum(p["lib"] not in local for p in final),
            **{l["lib"]: sum(p["lib"] == l["lib"] for p in final) for l in LOCAL_LIBS},
        },
        "objects": [p["name"] for p in final],
    }, indent=1) + "\n")
    print(f"wrote {len(final)} objects in {nlibs} libs; named {ndefs} defined and {nrefs} referenced symbols")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Regenerate the status block in README.md from the current build.

Run after `ninja`:
    python tools/update_status.py

Rewrites the text between the `status:begin` / `status:end` markers with the DOL match state,
objdiff progress and the number of imported library files per source. Every other doc links to this block
instead of repeating numbers, so nothing else goes stale.
"""

import datetime
import json
import re
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
BEGIN, END = "<!-- status:begin -->", "<!-- status:end -->"


def run(*cmd):
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True).stdout


def main():
    sha = run(str(ROOT / ("build/tools/dtk" + (".exe" if os.name == "nt" else ""))), "shasum", "-c", "config/GEAE8P/build.sha1")
    if not re.search(r"main\.dol: \S*OK", sha):
        sys.exit("main.dol doesn't match (or isn't built); run `ninja` and fix that first")
    progress = re.sub(r"\x1b\[[0-9;]*m", "", run(sys.executable, "configure.py", "progress"))

    def category(title):
        m = re.search(rf"{title}: ([\d.]+)% fuzzy, ([\d.]+)% matched, ([\d.]+)% linked \((\d+) / (\d+) files\)\s+"
                      rf"Code: (\d+) / (\d+) bytes \((\d+) / (\d+) functions\)\s+"
                      rf"Data: (\d+) / (\d+) bytes", progress)
        if not m:
            sys.exit(f"couldn't parse '{title}' from `configure.py progress`")
        return dict(fuzzy=float(m.group(1)), pct=float(m.group(2)), linked=float(m.group(3)),
                    files=int(m.group(4)), files_total=int(m.group(5)), code=int(m.group(6)),
                    code_total=int(m.group(7)), funcs=int(m.group(8)), funcs_total=int(m.group(9)),
                    data=int(m.group(10)), data_total=int(m.group(11)))

    all_, game, sdk, mw = category("All"), category("Game Code"), category("SDK Code"), category("Middleware")
    counts = json.loads((ROOT / "config/GEAE8P/lib_import.json").read_text())["counts"]
    today = datetime.date.today().isoformat()
    block = f"""{BEGIN}
_Generated by `tools/update_status.py` on {today}._

| | |
|---|---|
| `main.dol` | rebuilds byte-identical |
| All code matched | {all_['code']:,} / {all_['code_total']:,} bytes ({all_['pct']:.2f}%), {all_['funcs']:,} / {all_['funcs_total']:,} functions ({all_['fuzzy']:.2f}% fuzzy) |
| All data matched | {all_['data']:,} / {all_['data_total']:,} bytes ({100 * all_['data'] / all_['data_total']:.2f}%) |
| Linked from C | {all_['linked']:.2f}% of code, {all_['files']} / {all_['files_total']} files |
| Game code | {game['code']:,} / {game['code_total']:,} bytes ({game['pct']:.2f}%), {game['funcs']:,} / {game['funcs_total']:,} functions, {game['files']} of {game['files_total']} files linked |
| Library code (SDK/MSL/TRK) | {sdk['code']:,} / {sdk['code_total']:,} bytes, {sdk['funcs']:,} / {sdk['funcs_total']:,} functions, {sdk['files']} files linked ({counts['tw2004']} imported from tw2004) |
| Middleware (MusyX) | {mw['code']:,} bytes, {mw['funcs']:,} functions, {mw['files']} files linked ({counts['musyx']} imported from AxioDL/musyx) |
{END}"""
    text = README.read_text()
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        sys.exit(f"README.md has no {BEGIN} marker")
    README.write_text(text)
    print(block)


if __name__ == "__main__":
    main()
